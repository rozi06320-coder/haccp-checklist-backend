import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { baladiyahDraftCurriculum } from "../src/lib/training/baladiyah-draft-curriculum.js";

const migrationPath = fileURLToPath(
  new URL("../supabase/migrations/20261015003000_seed_baladiyah_single_active_org.sql", import.meta.url),
);
const manifestJson = JSON.stringify(baladiyahDraftCurriculum, null, 2);
const contentHash = createHash("sha256").update(manifestJson).digest("hex");

if (manifestJson.includes("$manifest$")) {
  throw new Error("Draft curriculum contains the reserved SQL delimiter $manifest$.");
}

const migration = `-- Generated by scripts/generate-baladiyah-single-active-org-seed.ts.
-- Seeds the existing Phase B1+B2 draft into exactly one active organization.
-- It never publishes content and never creates media, assignments, or enrollments.

create or replace function private.seed_baladiyah_single_active_organization()
returns table(course_id uuid, course_version_id uuid)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  manifest constant jsonb := $manifest$
${manifestJson}
$manifest$::jsonb;
  manifest_hash constant text := '${contentHash}';
  active_organization_count integer;
  target_organization_id uuid;
  saved_course_id uuid;
  saved_version_id uuid;
  exact_match boolean;
  module_record record;
  lesson_record record;
  saved_module_id uuid;
begin
  select count(*)::integer, (array_agg(organization.id))[1]
  into active_organization_count, target_organization_id
  from public.organizations organization
  where organization.active;

  if active_organization_count <> 1 then
    raise exception 'Baladiyah draft seed requires exactly one active organization; found %',
      active_organization_count
      using errcode = '55000';
  end if;

  if exists (
    select 1
    from public.training_courses course
    where course.course_key = manifest #>> '{course,course_key}'
      and course.organization_id <> target_organization_id
  ) then
    raise exception 'Baladiyah course key already belongs to a different organization'
      using errcode = '55000';
  end if;

  select course.id
  into saved_course_id
  from public.training_courses course
  where course.organization_id = target_organization_id
    and course.course_key = manifest #>> '{course,course_key}';

  if saved_course_id is not null then
    select version.id
    into saved_version_id
    from public.training_course_versions version
    where version.organization_id = target_organization_id
      and version.course_id = saved_course_id
      and version.version_number = (manifest #>> '{course,version_number}')::integer;

    select
      course.status = 'active'
      and course.archived_at is null
      and version.id is not null
      and version.organization_id = target_organization_id
      and version.status = 'draft'
      and version.default_locale = manifest #>> '{course,default_locale}'
      and version.supported_locales = array(
        select jsonb_array_elements_text(manifest #> '{course,supported_locales}')
      )
      and version.title_i18n = manifest #> '{course,title_i18n}'
      and version.description_i18n = manifest #> '{course,description_i18n}'
      and version.content_schema_version = (manifest ->> 'manifest_schema_version')::integer
      and version.revision = 0
      and version.content_hash = manifest_hash
      and version.published_at is null
      and version.published_by is null
      and version.retired_at is null
      and version.retired_by is null
      and (select count(*) from public.training_course_versions existing_version
           where existing_version.course_id = saved_course_id) = 1
      and (select count(*) from public.training_modules module
           where module.course_version_id = saved_version_id) = 9
      and (select count(*) from public.training_lessons lesson
           where lesson.course_version_id = saved_version_id) = 27
      and not exists (
        select 1
        from jsonb_array_elements(manifest -> 'modules') expected(module_value)
        left join public.training_modules module
          on module.course_version_id = saved_version_id
         and module.organization_id = target_organization_id
         and module.stable_key = expected.module_value ->> 'stable_key'
        where module.id is null
           or module.position is distinct from (expected.module_value ->> 'position')::integer
           or module.category_key is distinct from expected.module_value ->> 'category_key'
           or module.title_i18n is distinct from expected.module_value -> 'title_i18n'
           or module.description_i18n is distinct from expected.module_value -> 'description_i18n'
           or module.metadata is distinct from expected.module_value -> 'metadata'
      )
      and not exists (
        select 1
        from jsonb_array_elements(manifest -> 'modules') expected_module(module_value)
        cross join lateral jsonb_array_elements(expected_module.module_value -> 'lessons') expected_lesson(lesson_value)
        join public.training_modules module
          on module.course_version_id = saved_version_id
         and module.organization_id = target_organization_id
         and module.stable_key = expected_module.module_value ->> 'stable_key'
        left join public.training_lessons lesson
          on lesson.course_version_id = saved_version_id
         and lesson.organization_id = target_organization_id
         and lesson.module_id = module.id
         and lesson.stable_key = expected_lesson.lesson_value ->> 'stable_key'
        where lesson.id is null
           or lesson.position is distinct from (expected_lesson.lesson_value ->> 'position')::integer
           or lesson.lesson_type is distinct from expected_lesson.lesson_value ->> 'lesson_type'
           or lesson.required is distinct from (expected_lesson.lesson_value ->> 'required')::boolean
           or lesson.title_i18n is distinct from expected_lesson.lesson_value -> 'title_i18n'
           or lesson.objective_i18n is distinct from expected_lesson.lesson_value -> 'objective_i18n'
           or lesson.content_i18n is distinct from expected_lesson.lesson_value -> 'content_i18n'
           or lesson.estimated_duration_seconds is distinct from (expected_lesson.lesson_value ->> 'estimated_duration_seconds')::integer
           or lesson.minimum_engagement_seconds is distinct from (expected_lesson.lesson_value ->> 'minimum_engagement_seconds')::integer
           or lesson.pass_threshold_bps is distinct from (expected_lesson.lesson_value ->> 'pass_threshold_bps')::integer
           or lesson.max_attempts is not null
           or lesson.retry_delay_seconds <> 0
           or lesson.metadata is distinct from expected_lesson.lesson_value -> 'metadata'
      )
    into exact_match
    from public.training_courses course
    left join public.training_course_versions version on version.id = saved_version_id
    where course.id = saved_course_id
      and course.organization_id = target_organization_id;

    if coalesce(exact_match, false) then
      return query select saved_course_id, saved_version_id;
      return;
    end if;

    raise exception 'Existing Baladiyah course/version conflicts with the approved draft manifest'
      using errcode = '55000';
  end if;

  insert into public.training_courses(organization_id, course_key, status)
  values(target_organization_id, manifest #>> '{course,course_key}', 'active')
  returning id into saved_course_id;

  insert into public.training_course_versions(
    organization_id, course_id, version_number, status, default_locale, supported_locales,
    title_i18n, description_i18n, content_schema_version, revision, content_hash
  ) values(
    target_organization_id,
    saved_course_id,
    (manifest #>> '{course,version_number}')::integer,
    'draft',
    manifest #>> '{course,default_locale}',
    array(select jsonb_array_elements_text(manifest #> '{course,supported_locales}')),
    manifest #> '{course,title_i18n}',
    manifest #> '{course,description_i18n}',
    (manifest ->> 'manifest_schema_version')::integer,
    0,
    manifest_hash
  ) returning id into saved_version_id;

  for module_record in
    select value as module_value
    from jsonb_array_elements(manifest -> 'modules')
    order by (value ->> 'position')::integer
  loop
    insert into public.training_modules(
      organization_id, course_version_id, stable_key, position, category_key,
      title_i18n, description_i18n, metadata
    ) values(
      target_organization_id,
      saved_version_id,
      module_record.module_value ->> 'stable_key',
      (module_record.module_value ->> 'position')::integer,
      module_record.module_value ->> 'category_key',
      module_record.module_value -> 'title_i18n',
      module_record.module_value -> 'description_i18n',
      module_record.module_value -> 'metadata'
    ) returning id into saved_module_id;

    for lesson_record in
      select value as lesson_value
      from jsonb_array_elements(module_record.module_value -> 'lessons')
      order by (value ->> 'position')::integer
    loop
      insert into public.training_lessons(
        organization_id, course_version_id, module_id, stable_key, position, lesson_type,
        required, title_i18n, objective_i18n, content_i18n, estimated_duration_seconds,
        minimum_engagement_seconds, pass_threshold_bps, metadata
      ) values(
        target_organization_id,
        saved_version_id,
        saved_module_id,
        lesson_record.lesson_value ->> 'stable_key',
        (lesson_record.lesson_value ->> 'position')::integer,
        lesson_record.lesson_value ->> 'lesson_type',
        (lesson_record.lesson_value ->> 'required')::boolean,
        lesson_record.lesson_value -> 'title_i18n',
        lesson_record.lesson_value -> 'objective_i18n',
        lesson_record.lesson_value -> 'content_i18n',
        (lesson_record.lesson_value ->> 'estimated_duration_seconds')::integer,
        (lesson_record.lesson_value ->> 'minimum_engagement_seconds')::integer,
        (lesson_record.lesson_value ->> 'pass_threshold_bps')::integer,
        lesson_record.lesson_value -> 'metadata'
      );
    end loop;
  end loop;

  return query select saved_course_id, saved_version_id;
end;
$function$;

revoke all on function private.seed_baladiyah_single_active_organization()
  from public, anon, authenticated, service_role;

do $seed$
begin
  perform * from private.seed_baladiyah_single_active_organization();
end;
$seed$;

comment on function private.seed_baladiyah_single_active_organization() is
  'Owner-only successor seed for the approved Baladiyah draft. Requires exactly one active organization and fails closed on content conflicts.';
`;

writeFileSync(migrationPath, migration);
